keys = ["name", "age", "city", "job"]
values = ["Thanush", 18, "rajam", "Student"]
person = dict(zip(keys, values))

print("Keys list:", keys)
print("Values list:", values)
print("Combined Dictionary:", person)


#output
#Keys list: ['name', 'age', 'city', 'job']
#Values list: ['Thanush', 18, 'rajam', 'Student']
#Combined Dictionary: {'name': 'Thanush', 'age': 18, 'city': 'rajam', 'job': 'Student'}
