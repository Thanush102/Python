Tuple = (2,34,15,67,40,23,16,96)
n=len(Tuple)
print("Original Tuple",Tuple)
print("First half of Tuple:",Tuple[:(n//2)])
print("Second half of Tuple:",Tuple[(n//2):])


#OUTPUT
#Original Tuple (2, 34, 15, 67, 40, 23, 16, 96)
#First half of Tuple: (2, 34, 15, 67)
#Second half of Tuple: (40, 23, 16, 96)

